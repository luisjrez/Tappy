import sys

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import MetaData

from quality.databases import IsolationError, disposable_database, isolated_test_server
from tappy.models import metadata
from tappy.platform.schema import alembic_config


def verify_migrations(server_url: str, metadata: MetaData) -> list[str]:
    with disposable_database(server_url) as database_url:
        config = alembic_config(database_url)
        config.attributes["target_metadata"] = metadata
        command.upgrade(config, "head")
        command.downgrade(config, "base")
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as drift:
            return [str(drift)]
    return []


def main() -> int:
    try:
        server_url = isolated_test_server()
    except IsolationError as error:
        print(error, file=sys.stderr)
        return 1
    problems = verify_migrations(server_url, metadata)
    for problem in problems:
        print(problem, file=sys.stderr)
    if not problems:
        print("Migrations apply, roll back to base, reapply and match the models")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
